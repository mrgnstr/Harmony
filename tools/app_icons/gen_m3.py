#!/usr/bin/env python3
"""The app's launcher icons: python3 -I tools/app_icons/gen_m3.py

Draws every shape (set_shapes.py) in the system's colours and in each accent preset, writes the resources to
design/app-icons-shapes/res, copies them into app/src/main/res and rewrites the manifest's alias block:
  drawable-v31/   background + foreground in @android:color/system_* (follow the wallpaper, API 31+)
  drawable/       the same in the fallback palette (API 26-30), the monochrome layer, the preset-colour foregrounds
  mipmap-*        adaptive icon xml, legacy PNGs (fallback palette)
Also writes previews beside them (design/ is not tracked). The preview palettes only approximate Monet's.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from PIL import Image, ImageDraw  # noqa: E402

import gen  # noqa: E402
import lib  # noqa: E402
import set_shapes  # noqa: E402

OUT = os.path.join(gen.ROOT, "design", "app-icons-shapes")
FALLBACK = lib.monet(305)  # near the app's FallbackSeed (#6750A4)
WALLPAPERS = [("fallback", FALLBACK), ("blue", lib.monet(275)), ("green", lib.monet(150)),
              ("orange", lib.monet(45)), ("pink", lib.monet(350)), ("yellow", lib.monet(95))]


def export(i, icon, name="ic_launcher", res=None):
    d = os.path.join(OUT, f"{i + 1:02d}-{icon.slug}")
    res = res or os.path.join(d, "res")
    adaptive = gen.ADAPTIVE.replace("ic_launcher", name)
    lib.PALETTE = FALLBACK
    for dyn, folder in ((False, "drawable"), (True, "drawable-v31")):
        lib.DYNAMIC = dyn
        gen.write(os.path.join(res, folder, f"{name}_background.xml"), lib.vd_doc(icon.bg))
        gen.write(os.path.join(res, folder, f"{name}_foreground.xml"), lib.vd_doc(icon.fg))
    lib.DYNAMIC = False
    gen.write(os.path.join(res, "drawable", f"{name}_monochrome.xml"), lib.vd_doc(icon.mono))
    gen.write(os.path.join(res, "mipmap-anydpi-v26", f"{name}.xml"), adaptive)
    gen.write(os.path.join(res, "mipmap-anydpi-v26", f"{name}_round.xml"), adaptive)
    for layer, items in (("background", icon.bg), ("foreground", icon.fg), ("monochrome", icon.mono)):
        gen.write(os.path.join(d, "svg", layer + ".svg"), lib.layer_svg(items))
    sq, rd = gen.legacy(icon, False), gen.legacy(icon, True)
    for dpi, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        os.makedirs(os.path.join(res, f"mipmap-{dpi}"), exist_ok=True)
        sq.resize((px, px), Image.LANCZOS).save(os.path.join(res, f"mipmap-{dpi}", f"{name}.png"), optimize=True)
        rd.resize((px, px), Image.LANCZOS).save(os.path.join(res, f"mipmap-{dpi}", f"{name}_round.png"), optimize=True)
    gen.render(gen.composite(icon, "square"), 512, "play").convert("RGB").save(os.path.join(d, "play-512.png"), optimize=True)
    return sq, rd


# The accent presets, as in core/model/AccentColor.kt (keep the two lists the same).
ACCENTS = [("Red", "#E5484D"), ("Orange", "#F0803C"), ("Yellow", "#E0B000"), ("Green", "#3FA34D"),
           ("Teal", "#1E9E94"), ("Blue", "#3B7DE9"), ("Purple", "#7A5AF8"), ("Pink", "#E0559A")]
APP = os.path.join(gen.ROOT, "app", "src", "main")
BEGIN, END = "<!-- launcher-aliases:begin (generated by tools/app_icons/gen_m3.py) -->", "<!-- launcher-aliases:end -->"


def base_name(icon):
    return "ic_launcher" if icon.slug == "cookie" else "ic_launcher_" + icon.slug


def export_accents(icons, res):
    """Each shape in each preset colour: a foreground vector and an adaptive icon. No PNGs: below API 26 a coloured
    icon falls back to the shape's ordinary legacy icon through a resource alias."""
    values = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/app_icons/gen_m3.py. -->", "<resources>"]
    lib.DYNAMIC = False
    for accent, seed in ACCENTS:
        lib.PALETTE = lib.monet(lib.hue_of(seed))
        c = accent.lower()
        values.append(f'    <color name="launcher_bg_{c}">{lib.PALETTE["a2.100"]}</color>')
        for icon in icons:
            name = f"ic_launcher_{icon.slug}_{c}"
            gen.write(os.path.join(res, "drawable", f"{name}_foreground.xml"), lib.vd_doc(icon.fg))
            gen.write(os.path.join(res, "mipmap-anydpi-v26", f"{name}.xml"),
                      '<?xml version="1.0" encoding="utf-8"?>\n'
                      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                      f'    <background android:drawable="@color/launcher_bg_{c}" />\n'
                      f'    <foreground android:drawable="@drawable/{name}_foreground" />\n'
                      f'    <monochrome android:drawable="@drawable/{base_name(icon)}_monochrome" />\n'
                      '</adaptive-icon>\n')
            values.append(f'    <item name="{name}" type="mipmap">@mipmap/{base_name(icon)}</item>')
    gen.write(os.path.join(res, "values", "launcher_icons.xml"), "\n".join(values + ["</resources>", ""]))
    lib.PALETTE = FALLBACK


def aliases(icons):
    out = [BEGIN]
    for accent in [""] + [a for a, _ in ACCENTS]:
        for icon in icons:
            res = base_name(icon) if not accent else f"ic_launcher_{icon.slug}_{accent.lower()}"
            on = "true" if not accent and icon.slug == "cookie" else "false"
            rnd = f'\n            android:roundIcon="@mipmap/{res}_round"' if not accent else ""
            out.append(f'''        <activity-alias
            android:name=".launcher.{icon.slug.capitalize()}{accent}"
            android:enabled="{on}"
            android:exported="true"
            android:icon="@mipmap/{res}"{rnd}
            android:targetActivity=".app.MainActivity">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>''')
    return "\n".join(out + ["        " + END])


def install(icons):
    """Copies the generated res tree into the app and rewrites the manifest's alias block."""
    import shutil
    shutil.copytree(os.path.join(OUT, "res"), os.path.join(APP, "res"), dirs_exist_ok=True)
    path = os.path.join(APP, "AndroidManifest.xml")
    text = open(path).read()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    open(path, "w").write(text[:a] + aliases(icons) + text[b:])


def accent_sheet(icons, px=96):
    rows = [("Wallpaper", FALLBACK)] + [(a, lib.monet(lib.hue_of(s))) for a, s in ACCENTS]
    gap, left, top = 12, 110, 44
    im = Image.new("RGBA", (left + len(icons) * (px + gap) + gap, top + len(rows) * (px + gap) + gap), gen.BG)
    dr = ImageDraw.Draw(im)
    for j, icon in enumerate(icons):
        dr.text((left + j * (px + gap), 16), icon.title, font=gen.font(13, True), fill=gen.INK)
    for r, (name, pal) in enumerate(rows):
        lib.PALETTE = pal
        y = top + r * (px + gap)
        dr.text((gap, y + px / 2 - 9), name, font=gen.font(15, True), fill=gen.INK)
        for j, icon in enumerate(icons):
            im.alpha_composite(gen.render(gen.composite(icon, "circle"), px, "a"), (left + j * (px + gap), y))
    lib.PALETTE = FALLBACK
    return im


def wallpapers(icons, legacy, px=132):
    cols = [n for n, _ in WALLPAPERS] + ["themed", "themed dark", "legacy", "safe zone"]
    gap, left, top = 16, 150, 56
    W, H = left + len(cols) * (px + gap) + gap, top + len(icons) * (px + gap) + gap
    im = Image.new("RGBA", (W, H), gen.BG)
    dr = ImageDraw.Draw(im)
    for j, c in enumerate(cols):
        dr.text((left + j * (px + gap), 22), c, font=gen.font(15, True), fill=gen.INK)
    for r, icon in enumerate(icons):
        y = top + r * (px + gap)
        dr.text((gap, y + px / 2 - 22), f"{r + 1:02d}  {icon.title}", font=gen.font(18, True), fill=gen.INK)
        dr.text((gap, y + px / 2 + 4), icon.style, font=gen.font(12), fill=gen.SUB)
        for j, (_, pal) in enumerate(WALLPAPERS):
            lib.PALETTE = pal
            im.alpha_composite(gen.render(gen.composite(icon, "circle"), px, "w"), (left + j * (px + gap), y))
        lib.PALETTE = FALLBACK
        x = left + len(WALLPAPERS) * (px + gap)
        im.alpha_composite(gen.render(gen.composite(icon, "circle", "light"), px, "w"), (x, y))
        im.alpha_composite(gen.render(gen.composite(icon, "circle", "dark"), px, "w"), (x + px + gap, y))
        im.alpha_composite(legacy[r].resize((px, px), Image.LANCZOS), (x + 2 * (px + gap), y))
        im.alpha_composite(gen.render(gen.composite(icon, "square", guides=True), px, "w"), (x + 3 * (px + gap), y))
    return im


def main():
    icons = set_shapes.ICONS
    # One res tree to copy into app/src/main/res, each variant under its own name.
    res = os.path.join(OUT, "res")
    legacy = [export(i, icon, base_name(icon), res)[0] for i, icon in enumerate(icons)]
    export_accents(icons, res)
    install(icons)
    accent_sheet(icons).convert("RGB").save(os.path.join(OUT, "accents.png"), optimize=True)
    wallpapers(icons, legacy).convert("RGB").save(os.path.join(OUT, "wallpapers.png"), optimize=True)
    nums = list(range(1, len(icons) + 1))
    for name, pal in WALLPAPERS[:4]:
        lib.PALETTE = pal
        gen.overview(icons, nums, cols=5, title=f"Harmony · launcher icons · {name} palette").convert("RGB").save(
            os.path.join(OUT, f"overview-{name}.png"), optimize=True)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
