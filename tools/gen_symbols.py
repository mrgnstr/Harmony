#!/usr/bin/env python3
"""
Material Symbols (Rounded) for the app: subsets the variable font to the icons in ICONS and writes

  app/src/main/res/font/symbols_rounded.ttf          variable (FILL, wght, GRAD, opsz), used on API 26+
  app/src/main/res/font/symbols_rounded_outline.ttf  static FILL 0, wght 400, used below API 26
  app/src/main/res/font/symbols_rounded_filled.ttf   static FILL 1, wght 400, used below API 26
  .../core/designsystem/icons/Symbols.kt              name -> codepoint

The static fonts are cut from the same subset, so glyph metrics match between the two paths.
Source: icons/MaterialSymbolsRounded.ttf + .codepoints (github.com/google/material-design-icons, variablefont/).
Run: python3 -I tools/gen_symbols.py   (needs fontTools)
"""
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

# Symbol name in Kotlin -> Material Symbols name. Add a line and re-run to use a new icon.
ICONS = {
    "Home": "home",
    "Library": "library_music",
    "Search": "search",
    "Play": "play_arrow",
    "Pause": "pause",
    "SkipNext": "skip_next",
    "SkipPrevious": "skip_previous",
    "Shuffle": "shuffle",
    "Repeat": "repeat",
    "RepeatOne": "repeat_one",
    "MusicNote": "music_note",
    "Album": "album",
    "Person": "person",
    "Artist": "artist",
    "QueueMusic": "queue_music",
    "Settings": "settings",
    "MoreVert": "more_vert",
    "Favorite": "favorite",
    "Star": "star",
    "Close": "close",
    "ArrowBack": "arrow_back",
    "Check": "check",
    "Add": "add",
    "Sort": "sort",
    "Lyrics": "lyrics",
    "ExpandMore": "keyboard_arrow_down",
    "ChevronRight": "chevron_right",
    "History": "history",
    "Palette": "palette",
    "Tune": "tune",
    "Folder": "folder",
    "PlaylistAdd": "playlist_add",
    "Delete": "delete",
    "Edit": "edit",
    "Image": "image",
    "Info": "info",
    "VolumeUp": "volume_up",
    "VolumeMute": "volume_mute",
    "GraphicEq": "graphic_eq",
    "Genres": "category",
    "PlayNext": "queue_play_next",
    "DragHandle": "drag_handle",
    "Refresh": "refresh",
    "DarkMode": "dark_mode",
    "LightMode": "light_mode",
    "GridView": "grid_view",
    "ListView": "list",
}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "icons", "MaterialSymbolsRounded.ttf")
CODEPOINTS = os.path.join(ROOT, "icons", "MaterialSymbolsRounded.codepoints")
FONT_DIR = os.path.join(ROOT, "app", "src", "main", "res", "font")
KT = os.path.join(ROOT, "app", "src", "main", "java", "com", "mrgnstr", "harmony", "core", "designsystem", "icons", "Symbols.kt")


def main() -> None:
    points = {}
    with open(CODEPOINTS) as f:
        for line in f:
            name, cp = line.split()
            points[name] = int(cp, 16)
    missing = [n for n in ICONS.values() if n not in points]
    if missing:
        sys.exit(f"not in the font: {missing}")

    font = TTFont(SRC)
    options = subset.Options()
    options.layout_features = []  # looked up by codepoint, the ligatures are not needed
    options.hinting = False
    options.name_IDs = ["*"]
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=sorted({points[n] for n in ICONS.values()}))
    sub.subset(font)
    os.makedirs(FONT_DIR, exist_ok=True)
    font.save(os.path.join(FONT_DIR, "symbols_rounded.ttf"))

    for fill, suffix in ((0, "outline"), (1, "filled")):
        static = instancer.instantiateVariableFont(TTFont(os.path.join(FONT_DIR, "symbols_rounded.ttf")),
                                                   {"FILL": fill, "wght": 400, "GRAD": 0, "opsz": 24})
        static.save(os.path.join(FONT_DIR, f"symbols_rounded_{suffix}.ttf"))

    os.makedirs(os.path.dirname(KT), exist_ok=True)
    with open(KT, "w") as f:
        f.write("// Generated by tools/gen_symbols.py, do not edit.\n")
        f.write("package com.mrgnstr.harmony.core.designsystem.icons\n\n")
        f.write("/** Material Symbols Rounded codepoints; draw with [SymbolIcon]. */\n")
        f.write("object Symbols {\n")
        for kt, name in ICONS.items():
            f.write(f"    val {kt} = Symbol('\\u{points[name]:04X}')\n")
        f.write("}\n")
    sizes = {n: os.path.getsize(os.path.join(FONT_DIR, n)) for n in os.listdir(FONT_DIR) if n.startswith("symbols_")}
    print(f"{len(ICONS)} icons; " + ", ".join(f"{n} {s // 1024} KB" for n, s in sorted(sizes.items())))


if __name__ == "__main__":
    main()
